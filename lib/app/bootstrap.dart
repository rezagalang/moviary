class BootstrapResult {
  const BootstrapResult({
    required this.database,
    required this.preferences,
    required this.onboardingCompleted,
    required this.authRepository,
    required this.initialUser,
  });

  final AppDatabase database;
  final AppPreferences preferences;
  final bool onboardingCompleted;
  final AuthRepository authRepository;
  final AuthUser? initialUser;
}

/// OAuth *web* client ID, passed with `--dart-define-from-file=env/dev.json`.
/// Client IDs are public identifiers, not secrets. Optional when
/// google-services.json already provides a default web client.
const String _serverClientId = String.fromEnvironment('GOOGLE_SERVER_CLIENT_ID');

/// Opens local storage, initializes Firebase and restores the saved session.
/// Nothing here needs network access.
Future<BootstrapResult> bootstrap() async {
  final database = AppDatabase.open();
  final store = SettingsStore(database, const SystemClock());
  final preferences = await LoadPreferences(SettingsRepositoryImpl(store))();
  final onboardingCompleted = await OnboardingRepositoryImpl(store).isCompleted();

  await Firebase.initializeApp(options: DefaultFirebaseOptions.currentPlatform);
  final authRepository = FirebaseAuthRepository(
    FirebaseAuth.instance,
    GoogleSignInCredentialSource(
      serverClientId: _serverClientId.isEmpty ? null : _serverClientId,
    ),
  );

  // Firebase Auth persists the session on the device. The first auth-state
  // event carries it without a network round trip. The timeout is only a
  // safety net so the splash can never hang.
  final initialUser = await authRepository.authStateChanges().first.timeout(
        const Duration(seconds: 5),
        onTimeout: () => authRepository.currentUser,
      );

  return BootstrapResult(
    database: database,
    preferences: preferences,
    onboardingCompleted: onboardingCompleted,
    authRepository: authRepository,
    initialUser: initialUser,
  );
}